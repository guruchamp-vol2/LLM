"""Cleaning source code for pretraining (the code half of the data pipeline).

Filters follow the published recipes for code models (Codex, The Stack / StarCoder,
OpenCoder): drop files that are too big or small, minified or data-like, auto-generated,
or (for Python) that don't parse as Python 3. Secrets are replaced with placeholders,
and emails and IPs are redacted with the same code as web text.

Only permissive licences are kept by default, as in The Stack.
"""

from __future__ import annotations

import ast
import re
import warnings
from dataclasses import dataclass, field

from .pii import redact_pii

PERMISSIVE = frozenset({"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "cc0-1.0", "unlicense"})

_GENERATED = re.compile(r"auto[- ]?generated|generated by|do not edit|autogenerated", re.I)

# Common secret formats (the patterns secret scanners look for). Replaced, not dropped,
# so the surrounding code still teaches the model how keys are used.
_SECRETS = [
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----.*?-----END [A-Z ]*PRIVATE KEY-----", re.S), "<PRIVATE_KEY>"),
    (re.compile(r"\b(AKIA|ASIA)[0-9A-Z]{16}\b"), "<AWS_KEY_ID>"),
    (re.compile(r"\bgh[pousr]_[A-Za-z0-9]{36,}\b"), "<GITHUB_TOKEN>"),
    (re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b"), "<SLACK_TOKEN>"),
    (re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b"), "<GOOGLE_API_KEY>"),
    (re.compile(r"\bsk-[A-Za-z0-9_\-]{20,}\b"), "<API_KEY>"),
    # key = "long random string" for names that say they are secret
    (re.compile(r"""((?:api[_-]?key|secret|token|passw(?:or)?d|access[_-]?key)["']?\s*[:=]\s*["'])"""
                r"""([A-Za-z0-9+/_\-]{16,})(["'])""", re.I), r"\1<SECRET>\3"),
]


def redact_secrets(code: str) -> tuple[str, int]:
    n = 0
    for pat, rep in _SECRETS:
        code, k = pat.subn(rep, code)
        n += k
    return code, n


@dataclass
class CodeFilterConfig:
    min_chars: int = 100
    max_chars: int = 100_000
    max_line_len: int = 1000
    max_mean_line_len: float = 100.0
    min_alnum_frac: float = 0.25
    max_digit_frac: float = 0.5     # mostly numbers = a data file
    min_lines: int = 3
    python_must_parse: bool = True
    licenses: frozenset | None = field(default=PERMISSIVE)  # None = keep any licence


def code_filter(code: str, language: str = "", license: str = "", cfg: CodeFilterConfig | None = None) -> str | None:
    """None if the file should be kept, else the reason it was dropped."""
    cfg = cfg or CodeFilterConfig()
    if cfg.licenses is not None and license and license.lower() not in cfg.licenses:
        return "license"
    n = len(code)
    if n < cfg.min_chars:
        return "too_short"
    if n > cfg.max_chars:
        return "too_long"
    lines = code.splitlines()
    if len(lines) < cfg.min_lines:
        return "too_few_lines"
    if max(map(len, lines)) > cfg.max_line_len:
        return "long_line"
    if n / len(lines) > cfg.max_mean_line_len:
        return "mean_line_len"
    if sum(c.isalnum() for c in code) / n < cfg.min_alnum_frac:
        return "alnum"
    if sum(c.isdigit() for c in code) / n > cfg.max_digit_frac:
        return "data_file"
    if _GENERATED.search("\n".join(lines[:5])):
        return "generated"
    if cfg.python_must_parse and language.lower() == "python":
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")  # invalid escape sequences etc. in old code
                ast.parse(code)
        except (SyntaxError, ValueError, MemoryError, RecursionError):
            return "python_syntax"
    return None


def clean_code(code: str) -> tuple[str, dict]:
    """Normalise line endings, strip trailing whitespace, redact secrets and PII."""
    code = code.replace("\r\n", "\n").replace("\r", "\n")
    code = "\n".join(line.rstrip() for line in code.split("\n")).strip("\n") + "\n"
    code, secrets = redact_secrets(code)
    code, pii = redact_pii(code)
    return code, {"secrets": secrets, "pii": pii}
